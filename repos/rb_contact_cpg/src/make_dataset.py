"""Build and export the contact-pressure dataset.

    python3 make_dataset.py [--n 4000] [--nodes 128] [--out ../data]

Writes:
    contact_pressures.npz   arrays + metadata (primary artifact)
    contact_pressures.csv   the same matrix, flat, for non-numpy tools
    DATASET.md              provenance and caveats
"""

from __future__ import annotations

import argparse
import json
import pathlib

import numpy as np

from contact_dataset import generate, hertz_shape_error


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=4000, help="number of samples")
    ap.add_argument("--nodes", type=int, default=128, help="contact nodes per sample")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--out", type=str, default="../data")
    ap.add_argument("--no-csv", action="store_true")
    args = ap.parse_args()

    out = pathlib.Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    print(f"generating {args.n} samples x {args.nodes} nodes ...")
    P, params, x, attempts = generate(
        n_samples=args.n, N=args.nodes, seed=args.seed
    )
    print(f"  accepted {len(P)} / {attempts} attempts "
          f"({100*len(P)/attempts:.1f}% -- rest were empty or edge contact)")

    # --- integrity checks, reported not assumed --------------------------
    assert P.min() >= 0.0, "pressures must be non-negative"
    support = (P > 1e-10).sum(axis=1)
    n_patches = np.array([
        int(np.sum(np.diff(np.concatenate([[0], (row > 1e-10).astype(int), [0]])) == 1))
        for row in P
    ])
    smooth = params[:, 2] == 0.0
    shape_err = np.array([hertz_shape_error(x, P[i]) for i in np.flatnonzero(smooth)])

    stats = {
        "n_samples": int(P.shape[0]),
        "n_nodes": int(P.shape[1]),
        "min": float(P.min()),
        "max": float(P.max()),
        "frac_zero_entries": float((P == 0).mean()),
        "support_min": int(support.min()),
        "support_max": int(support.max()),
        "support_mean": float(support.mean()),
        "patches_max": int(n_patches.max()),
        "frac_multi_patch": float((n_patches > 1).mean()),
        "hertz_shape_err_median_smooth": float(np.nanmedian(shape_err)),
        "seed": args.seed,
    }
    print(json.dumps(stats, indent=2))

    # --- split -----------------------------------------------------------
    rng = np.random.default_rng(args.seed + 1)
    perm = rng.permutation(len(P))
    n_tr = int(0.8 * len(P))
    tr, te = perm[:n_tr], perm[n_tr:]

    npz_path = out / "contact_pressures.npz"
    np.savez_compressed(
        npz_path,
        P=P, params=params, x=x,
        train_idx=tr, test_idx=te,
        param_names=np.array(["radius", "offset", "wav_amp", "wav_len", "delta"]),
        stats=json.dumps(stats),
    )
    print(f"\nwrote {npz_path}  ({npz_path.stat().st_size/1e6:.2f} MB)")

    if not args.no_csv:
        csv_path = out / "contact_pressures.csv"
        header = ",".join(f"p{i:03d}" for i in range(P.shape[1]))
        np.savetxt(csv_path, P, delimiter=",", header=header, comments="", fmt="%.8e")
        print(f"wrote {csv_path}  ({csv_path.stat().st_size/1e6:.2f} MB)")

    (out / "DATASET.md").write_text(_card(stats, args))
    print(f"wrote {out / 'DATASET.md'}")


def _card(s, args):
    return f"""# Contact pressure dataset

`contact_pressures.npz` — {s['n_samples']} contact-pressure fields, {s['n_nodes']} nodes each.

## What this is

Normal contact pressure `p(x)` on the contact line between a rigid indenter and
an elastic half-plane (2-D plane strain, frictionless). The pressure field **is**
the Lagrange multiplier of the non-interpenetration constraint — the quantity
Algorithm 2 of Benaceur/Ern/Ehrlacher (`hal-02081485v2`) compresses.

**Non-negative by construction**: `p >= 0` is a KKT condition, imposed as a bound
in the QP, not enforced afterwards by clipping.

## Provenance — read this

**Synthetic.** Generated by `src/contact_dataset.py` from a boundary-integral
(influence-coefficient) model, solved as a convex QP. Specifically:

- **Not** experimental measurements.
- **Not** FEM output, and **not** the paper's solver (the authors used FreeFem++).
- **Not** a reproduction of any figure in the paper.

Model assumptions: linear elasticity, small strains, frictionless contact,
half-plane geometry (so the indenter is small relative to the body), and
piecewise-constant pressure elements.

**Validation**: for a smooth parabolic indenter the solver reproduces the analytic
semi-elliptical Hertz profile (Johnson, *Contact Mechanics*, Ch. 4) to a median
relative shape error of **{s['hertz_shape_err_median_smooth']:.4f}**.

## Contents

| key | shape | meaning |
|---|---|---|
| `P` | ({s['n_samples']}, {s['n_nodes']}) | pressure fields, one per row, all `>= 0` |
| `params` | ({s['n_samples']}, 5) | `radius, offset, wav_amp, wav_len, delta` |
| `x` | ({s['n_nodes']},) | node coordinates on `[-0.5, 0.5]` |
| `train_idx` / `test_idx` | 80/20 | row indices of a fixed split |
| `param_names` | (5,) | column names for `params` |
| `stats` | JSON string | the summary below |

## Statistics

- zero entries: **{s['frac_zero_entries']:.1%}** — the data is genuinely sparse,
  because contact is confined to a patch
- support size: {s['support_min']}–{s['support_max']} nodes (mean {s['support_mean']:.1f})
- **{s['frac_multi_patch']:.1%}** of samples have more than one disjoint contact
  patch (up to {s['patches_max']}), from surface waviness
- value range: {s['min']:.3e} … {s['max']:.3e}
- seed: {s['seed']}

Samples whose contact patch touched a domain edge were rejected: there the
half-plane truncation dominates and the field is a box artifact, not physics.

## Load

```python
import numpy as np
d = np.load("contact_pressures.npz", allow_pickle=False)
P = d["P"]                       # (n, nodes), non-negative
Xtr, Xte = P[d["train_idx"]], P[d["test_idx"]]
```

## Notes for dictionary learning

Rows are samples, columns are spatial nodes. For NMF conventions expecting
`(features, samples)`, transpose: `T = P.T`.

Two properties make this different from MNIST as an NMF testbed:

1. Non-negativity is **physical**, not a pixel-intensity artifact — a negative
   contact pressure would mean the surfaces pull on each other.
2. The support **moves and splits** with the parameters. A parts-based
   factorization has to cover a continuum of patch positions and widths, so the
   number of atoms needed is a real question rather than a fixed part count.

The generating manifold is 5-dimensional (`params`), which gives a reference
point for how many atoms a method ought to need.

Regenerate: `python3 make_dataset.py --n {args.n} --nodes {args.nodes} --seed {args.seed}`
"""


if __name__ == "__main__":
    main()
